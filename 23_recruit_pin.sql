--------------------------------------------------------------------------------
-- 연세대학교 산학협력단 채용시스템 (RHR) - 채용공고 상단 고정
--
-- 사용자 화면(메인 · 채용공고 목록)에서 관리자가 고른 공고를 맨 위에 고정해 둘 수 있게 한다.
-- 고정한 공고는 접수가 마감된 뒤에도 관리자가 해제할 때까지 맨 위에 남는다(장기간 노출).
--
--   PIN_YN : 'Y' 고정 / 'N' 일반   (기존 공고는 모두 'N' 이라 화면이 달라지지 않는다)
--   PIN_DT : 고정한 시각 (해제하면 NULL)
--
-- ★ 순서: 반드시 이 스크립트를 먼저 실행하고, 그 다음에 새 애플리케이션을 배포한다.
--   새 애플리케이션은 PIN_YN 컬럼을 모든 채용공고 조회에 쓰므로, 컬럼이 없는 상태로 배포하면
--   메인 화면과 채용공고 목록이 열리지 않는다. (옛 애플리케이션은 이 컬럼을 모르는 채로
--   정상 동작하므로, 이 스크립트를 먼저 실행해 두는 것은 안전하다.)
--
-- 관리자 권한(시스템 / 채용 / 부서 담당자) 구분은 기존 TB_ADMIN.ROLE_CD(VARCHAR2(20)) 에
-- 'DEPT' 값을 더 쓰는 것이라 DB 변경이 없다. 부서 담당자 계정은 관리자 > 계정 화면에서 만든다.
--
-- 실행 : tbsql YSHR/비밀번호@tibero @23_recruit_pin.sql
--------------------------------------------------------------------------------

ALTER TABLE TB_RECRUIT ADD (
    PIN_YN  CHAR(1) DEFAULT 'N' NOT NULL,   -- 사용자 화면 상단 고정 여부
    PIN_DT  DATE                            -- 고정한 시각
);

COMMENT ON COLUMN TB_RECRUIT.PIN_YN IS '사용자 화면 목록 상단 고정 여부 (Y/N)';
COMMENT ON COLUMN TB_RECRUIT.PIN_DT IS '상단 고정한 시각';

COMMIT;

