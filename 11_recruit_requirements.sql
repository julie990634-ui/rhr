-- 연세대학교 산학협력단 채용시스템 (RHR) - 채용공고에 지원자격(학력 / 경력 / 자격) 입력란 추가
--
-- 공고 상세 화면에 '지원 자격' 으로 보여 줄 세 항목을 공고마다 따로 입력할 수 있게 한다.
-- 모두 선택 입력(NULL 허용)이라 기존 공고는 그대로 두면 되고, 이 스크립트를 실행해도 기존
-- 화면은 달라지지 않는다.
--
-- ★ 순서: 반드시 이 스크립트를 먼저 실행하고, 그 다음에 새 애플리케이션을 배포한다.
--   새 애플리케이션은 이 컬럼을 읽으므로, 컬럼이 없는 상태로 배포하면 채용공고 상세 화면과
--   관리자의 공고 등록/수정 화면에서 오류가 난다. (옛 애플리케이션은 이 컬럼을 모르는 채로
--   정상 동작하므로, 이 스크립트를 먼저 실행해 두는 것은 안전하다.)
--
-- 길이: 화면에서는 항목당 1000자까지 받는다. 한글이 바이트 기준으로 3바이트씩 잡히는 DB 설정이어도
--      들어가도록 컬럼은 4000 으로 넉넉하게 둔다.
--
-- 실행 : tbsql YSHR/비밀번호@tibero @11_recruit_requirements.sql
--------------------------------------------------------------------------------

ALTER TABLE TB_RECRUIT ADD (
    EDU_REQ     VARCHAR2(4000),     -- 학력사항 (지원 자격)
    CAREER_REQ  VARCHAR2(4000),     -- 경력사항 (지원 자격)
    CERT_REQ    VARCHAR2(4000)      -- 자격사항 (자격증 / 우대사항 등)
);

COMMENT ON COLUMN TB_RECRUIT.EDU_REQ    IS '지원 자격 - 학력사항 (줄바꿈 포함 일반 텍스트)';
COMMENT ON COLUMN TB_RECRUIT.CAREER_REQ IS '지원 자격 - 경력사항 (줄바꿈 포함 일반 텍스트)';
COMMENT ON COLUMN TB_RECRUIT.CERT_REQ   IS '지원 자격 - 자격사항 (줄바꿈 포함 일반 텍스트)';

COMMIT;

