-- ------------------------------------------------------------------------------
-- 지원자 비밀번호 초기화 지원
--
-- 관리자가 지원자의 조회용 비밀번호를 초기화하면 이 값이 'Y'가 되고,
-- 지원자는 다음 본인 확인(접수번호+비밀번호) 때 새 비밀번호로 바꾸기 전까지는
-- 지원서 조회/수정 화면에 들어갈 수 없다.
-- ------------------------------------------------------------------------------
ALTER TABLE TB_APPLICATION ADD (PWD_RESET_YN CHAR(1) DEFAULT 'N' NOT NULL);
COMMENT ON COLUMN TB_APPLICATION.PWD_RESET_YN IS '관리자가 비밀번호를 초기화했는지 (Y면 로그인 후 비밀번호부터 변경해야 함)';
