--------------------------------------------------------------------------------
-- 연세대학교 산학협력단 채용시스템 (RHR) - 접수 마감을 '시각'까지 지정
--
-- 지금까지 접수 마감은 마감일 하루가 모두 끝나야(다음 날 0시) 닫혔다.
-- 앞으로는 TB_RECRUIT.END_DT (DATE 타입이라 시각을 담을 수 있다) 의 시각까지 보고 닫는다.
-- 관리자 화면에서 마감 시각을 고르고, 비워 두면 17:00 으로 저장한다.
--
-- 컬럼 구조는 바뀌지 않는다. 다만 기존 공고의 END_DT 는 시각이 00:00 으로 들어 있어서,
-- 그대로 두면 새 애플리케이션이 "마감일 0시에 마감" 으로 읽어 마감일 당일에 바로 닫힌다.
-- 그래서 시각이 00:00 인 기존 공고는 마감일 17:00 으로 바꿔 준다.
--   (기존에는 마감일 23:59 까지 접수되던 공고가 17:00 에 마감되도록 바뀌는 점에 유의)
--   마감일 23:59 를 그대로 유지하려면 아래 UPDATE 의 17/24 를 (24*60-1)/(24*60) 로 바꿔 실행한다.
--
-- ★ 순서: 새 애플리케이션을 배포하기 직전(또는 직후 바로)에 이 스크립트를 실행한다.
--   옛 애플리케이션은 날짜(TRUNC)만 비교하므로 이 UPDATE 를 먼저 실행해도 동작이 달라지지 않는다.
--   → 가장 안전한 순서는 "이 스크립트 실행 → 새 애플리케이션 배포" 이다.
--
-- 실행 : tbsql YSHR/비밀번호@tibero @25_recruit_end_time.sql
--------------------------------------------------------------------------------

UPDATE TB_RECRUIT
   SET END_DT = TRUNC(END_DT) + 17/24
 WHERE END_DT = TRUNC(END_DT);

COMMIT;

