-- ------------------------------------------------------------------------------
-- 접근제어 (출발지 IP 허용 / 차단)와 차단 이력
--
-- 마스터접근제어 > 접근차단이력이 쓴다.
--   TB_ACCESS_IP_RULE   마스터가 등록한 출발지 규칙. BLOCK 에 걸리면 요청이 403 으로 막히고,
--                       ALLOW 에 있으면 BLOCK 에 걸려도 통과한다 (오차단 복구용).
--                       규칙이 하나도 없으면 아무 것도 막지 않는다.
--   TB_ACCESS_BLOCK_LOG 규칙으로 막힌 요청의 이력.
--
-- 규칙 조회에 실패하면(DB 장애, 이 스크립트를 실행하기 전) 요청은 막지 않고 통과시킨다.
-- ------------------------------------------------------------------------------
CREATE SEQUENCE SEQ_TB_ACCESS_IP_RULE START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_ACCESS_IP_RULE (
    RULE_ID     NUMBER(10)      NOT NULL,
    RULE_TYPE   VARCHAR2(10)    NOT NULL,
    IP_CIDR     VARCHAR2(50)    NOT NULL,
    NOTE        VARCHAR2(200),
    CREATED_BY  VARCHAR2(30),
    CREATED_DT  DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_ACCESS_IP_RULE PRIMARY KEY (RULE_ID),
    CONSTRAINT UK_TB_ACCESS_IP_RULE UNIQUE (RULE_TYPE, IP_CIDR),
    CONSTRAINT CK_TB_ACCESS_IP_RULE_TYPE CHECK (RULE_TYPE IN ('ALLOW', 'BLOCK'))
);

COMMENT ON TABLE  TB_ACCESS_IP_RULE            IS '출발지 IP 허용 / 차단 규칙';
COMMENT ON COLUMN TB_ACCESS_IP_RULE.RULE_ID    IS '규칙 번호';
COMMENT ON COLUMN TB_ACCESS_IP_RULE.RULE_TYPE  IS 'ALLOW(허용) / BLOCK(차단)';
COMMENT ON COLUMN TB_ACCESS_IP_RULE.IP_CIDR    IS 'IP 하나(203.0.113.5) 또는 IPv4 대역(203.0.113.0/24)';
COMMENT ON COLUMN TB_ACCESS_IP_RULE.NOTE       IS '등록 사유';
COMMENT ON COLUMN TB_ACCESS_IP_RULE.CREATED_BY IS '등록한 담당자';
COMMENT ON COLUMN TB_ACCESS_IP_RULE.CREATED_DT IS '등록 시각';

CREATE SEQUENCE SEQ_TB_ACCESS_BLOCK_LOG START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_ACCESS_BLOCK_LOG (
    BLOCK_ID    NUMBER(12)      NOT NULL,
    OCCUR_DT    DATE            DEFAULT SYSDATE NOT NULL,
    SRC_IP      VARCHAR2(45)    NOT NULL,
    REQ_PATH    VARCHAR2(300),
    REASON      VARCHAR2(40)    NOT NULL,
    HTTP_METHOD VARCHAR2(10),
    REQ_HEADER  VARCHAR2(2000),
    CONSTRAINT PK_TB_ACCESS_BLOCK_LOG PRIMARY KEY (BLOCK_ID)
);

CREATE INDEX IDX_ACCESS_BLOCK_LOG_DT ON TB_ACCESS_BLOCK_LOG (OCCUR_DT);
CREATE INDEX IDX_ACCESS_BLOCK_LOG_IP ON TB_ACCESS_BLOCK_LOG (SRC_IP, OCCUR_DT);

COMMENT ON TABLE  TB_ACCESS_BLOCK_LOG             IS '출발지 규칙으로 차단된 요청 이력';
COMMENT ON COLUMN TB_ACCESS_BLOCK_LOG.BLOCK_ID    IS '이력 번호';
COMMENT ON COLUMN TB_ACCESS_BLOCK_LOG.OCCUR_DT    IS '차단 시각';
COMMENT ON COLUMN TB_ACCESS_BLOCK_LOG.SRC_IP      IS '출발지 IP';
COMMENT ON COLUMN TB_ACCESS_BLOCK_LOG.REQ_PATH    IS '요청 경로 (쿼리스트링 제외)';
COMMENT ON COLUMN TB_ACCESS_BLOCK_LOG.REASON      IS '차단 사유 (blocked-ip 등)';
COMMENT ON COLUMN TB_ACCESS_BLOCK_LOG.HTTP_METHOD IS 'HTTP 메서드';
COMMENT ON COLUMN TB_ACCESS_BLOCK_LOG.REQ_HEADER  IS '요청 헤더 요약 (쿠키 · 인증 헤더 값은 ***)';
